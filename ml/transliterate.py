
"""Транслитерация латинских фэнтези-имён в кириллицу.

Используется как вспомогательный инструмент для расширения датасета
(см. этап 1 в roadmap). Основной датасет собирается из русских источников
напрямую; транслитерация — для имён из SRD/вики, где источник на латинице.

Использование:
    python ml/transliterate.py Aelioniel
    → Аэлиониэль
"""
import re
import sys

# Латинские согласные — для контекстного правила "l перед согласной".
# ВАЖНО: правило смотрит на ЛАТИНСКИЙ контекст, потому что на входе
# строка ещё не транслитерирована. Замена на "ль" уже даст кириллицу.
LATIN_CONSONANTS = "bcdfghjklmnpqrstvwxyz"

# Порядок важен: сначала длинные паттерны, потом контекстные, потом одиночные.
RULES = [
    # Финальное эльфийское -iel → -иэль (Aelioniel → Аэлиониэль).
    (r"iel$", "иэль"),
    # Мягкое 'l' перед ЛАТИНСКОЙ согласной → 'ль' (Silvanor → Сильванор).
    (rf"l(?=[{LATIN_CONSONANTS}])", "ль"),
    # Диграфы
    (r"shch", "щ"),
    (r"sch", "ш"),
    (r"sh", "ш"),
    (r"ch", "ч"),
    (r"th", "т"),
    (r"ph", "ф"),
    (r"kh", "х"),
    (r"zh", "ж"),
    (r"ts", "ц"),
    (r"ya", "я"),
    (r"yu", "ю"),
    (r"yo", "ё"),
    (r"ye", "е"),
    (r"ae", "аэ"),
    (r"ai", "ай"),
    (r"ei", "эй"),
    (r"ie", "иэ"),
    (r"ee", "и"),
    (r"oo", "у"),
    (r"ou", "у"),
    (r"au", "ау"),
    # Одиночные буквы
    (r"a", "а"), (r"b", "б"), (r"c", "к"), (r"d", "д"),
    (r"e", "е"), (r"f", "ф"), (r"g", "г"), (r"h", "х"),
    (r"i", "и"), (r"j", "дж"), (r"k", "к"), (r"l", "л"),
    (r"m", "м"), (r"n", "н"), (r"o", "о"), (r"p", "п"),
    (r"q", "к"), (r"r", "р"), (r"s", "с"), (r"t", "т"),
    (r"u", "у"), (r"v", "в"), (r"w", "в"), (r"x", "кс"),
    (r"y", "и"), (r"z", "з"),
]


def transliterate(name: str) -> str:
    """Транслитерирует латинское имя в кириллицу, делает первую букву заглавной."""
    result = name.lower()
    for pattern, repl in RULES:
        result = re.sub(pattern, repl, result)
    return result[:1].upper() + result[1:] if result else result


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Использование: python ml/transliterate.py <латинское_имя>")
        print("Пример: python ml/transliterate.py Aelioniel")
        sys.exit(1)
    print(transliterate(sys.argv[1]))